// Contact Inquiry Form Submission Handler
window.handleContactInquirySubmit = function(event) {
  if (event) event.preventDefault();
  const name = document.getElementById('inquiryName')?.value.trim();
  const phone = document.getElementById('inquiryPhone')?.value.trim();
  const email = document.getElementById('inquiryEmail')?.value.trim();
  const subject = document.getElementById('inquirySubject')?.value.trim() || 'General Inquiry';
  const message = document.getElementById('inquiryMessage')?.value.trim();

  if (!name || !phone || !message) {
    alert('कृपया नाम, मोबाइल नम्बर र सन्देश अनिवार्य रूपमा भर्नुहोस्।');
    return false;
  }

  const newInquiry = {
    id: `INQ-${Date.now().toString().slice(-4)}`,
    name,
    phone,
    email: email || 'N/A',
    subject,
    message,
    date: new Date().toISOString().slice(0, 10),
    status: 'New'
  };

  try {
    const raw = localStorage.getItem('npi_inquiries');
    const inquiries = raw ? JSON.parse(raw) : [];
    inquiries.unshift(newInquiry);
    localStorage.setItem('npi_inquiries', JSON.stringify(inquiries));
  } catch(e) {
    console.warn('Inquiry storage error', e);
  }

  const form = document.getElementById('contactInquiryForm');
  if (form) form.reset();

  alert(`धन्यवाद ${name} ज्यू! तपाईंको सोधपुछ सन्देश (ID: ${newInquiry.id}) निलकण्ठ बहुप्राविधिक शिक्षालयमा सफलतापूर्वक दर्ता भएको छ। हाम्रा प्रतिनिधिले छिट्टै सम्पर्क गर्नेछन्।`);
  return false;
};

