function getDynamicNotices() {
  try {
    const raw = localStorage.getItem('npi_notices');
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn('Error loading dynamic notices', e);
  }
  return defaultNoticesData;
}

let activeNoticeCategory = 'all';
let currentSearchQuery = '';

document.addEventListener('DOMContentLoaded', () => {
  initNoticesHub();
});

function initNoticesHub() {
  renderNoticesGrid();

  // Search input binding
  const searchInput = document.getElementById('noticesSearchInput');
  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      currentSearchQuery = e.target.value.toLowerCase().trim();
      renderNoticesGrid();
    });
  }

  // Filter tabs binding
  const filterTabs = document.querySelectorAll('.notice-filter-tab');
  filterTabs.forEach(tab => {
    tab.addEventListener('click', () => {
      filterTabs.forEach(t => t.classList.remove('active'));
      tab.classList.add('active');
      activeNoticeCategory = tab.getAttribute('data-filter') || 'all';
      renderNoticesGrid();
    });
  });
}

function renderNoticesGrid() {
  const container = document.getElementById('noticesGridContainer');
  if (!container) return;

  const isEn = (typeof currentLang !== 'undefined' && currentLang === 'en');
  const allNotices = getDynamicNotices();

  const filtered = allNotices.filter(item => {
    const matchCategory = (activeNoticeCategory === 'all') || (item.category === activeNoticeCategory);
    const title = isEn ? (item.title_en || item.title_ne) : item.title_ne;
    const content = isEn ? (item.content_en || item.content_ne) : item.content_ne;
    const matchSearch = !currentSearchQuery || 
      title.toLowerCase().includes(currentSearchQuery) || 
      content.toLowerCase().includes(currentSearchQuery) ||
      (item.categoryLabel_ne && item.categoryLabel_ne.toLowerCase().includes(currentSearchQuery));
    return matchCategory && matchSearch;
  });

  if (filtered.length === 0) {
    container.innerHTML = `
      <div style="grid-column: 1 / -1; text-align: center; padding: 3rem 1rem; color: var(--text-muted);">
        <i class="fa-regular fa-folder-open" style="font-size: 3rem; margin-bottom: 1rem; opacity: 0.5;"></i>
        <h4>${isEn ? 'No notices found matching your criteria.' : 'कुनै सूचना फेला परेन।'}</h4>
        <p style="font-size: 0.9rem;">${isEn ? 'Try adjusting your search terms or category filter.' : 'कृपया अन्य शब्द वा विधा छानेर खोज्नुहोस्।'}</p>
      </div>
    `;
    return;
  }

  container.innerHTML = filtered.map(notice => {
    const title = isEn ? (notice.title_en || notice.title_ne) : notice.title_ne;
    const categoryLabel = isEn ? (notice.categoryLabel_en || notice.categoryLabel_ne) : notice.categoryLabel_ne;
    const month = isEn ? notice.month_en : notice.month_ne;
    const newBadge = notice.isNew 
      ? `<span class="notice-badge badge-new">${isEn ? 'NEW' : 'नयाँ'}</span>` 
      : '';

    return `
      <div class="notice-card" onclick="viewNoticeDetail('${notice.id}')">
        <div class="notice-card-header">
          <div class="notice-date-box">
            <span class="notice-date-day">${notice.day}</span>
            <span class="notice-date-month">${month}</span>
          </div>
          <div class="notice-card-meta">
            <span class="notice-badge ${notice.catClass || 'cat-circular'}">${categoryLabel}</span>
            ${newBadge}
          </div>
        </div>

        <h4 class="notice-card-title">${title}</h4>

        <div class="notice-card-footer">
          <span class="notice-date-full">
            <i class="fa-regular fa-calendar"></i> ${notice.date_bs}
          </span>
          <span class="notice-read-more">
            ${isEn ? 'View Circular' : 'विवरण हेर्नुहोस्'} <i class="fa-solid fa-arrow-right"></i>
          </span>
        </div>
      </div>
    `;
  }).join('');
}

